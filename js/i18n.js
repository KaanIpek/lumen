  const I18N = {
    lang: 'en',
    STRINGS,
    detect() {
      const saved = Store && Store.lang;
      if (saved && STRINGS[saved]) return saved;
      const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
      return STRINGS[nav] ? nav : 'en';
    },
    set(lang) {
      this.lang = STRINGS[lang] ? lang : 'en';
      if (Store) Store.lang = this.lang;
      document.documentElement.setAttribute('lang', this.lang);
      this.apply();
      // apply() only touches data-i18n markup. Anything a screen drew for itself
      // has to be drawn again, or the language change stops at the edge of
      // index.html and every generated list keeps the old words.
      if (LUMEN.UI && LUMEN.UI.relocalize) LUMEN.UI.relocalize();
    },
    t(key, vars) {
      const dict = STRINGS[this.lang] || STRINGS.en;
      let s = dict[key];
      if (s == null) s = STRINGS.en[key];
      if (s == null) return key;
      if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
      return s;
    },
    // translate everything tagged in the DOM
    apply() {
      document.querySelectorAll('[data-i18n]').forEach((el) => {
        el.textContent = this.t(el.getAttribute('data-i18n'));
      });
      document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
        el.setAttribute('aria-label', this.t(el.getAttribute('data-i18n-aria')));
      });
      // Tooltips. A title is what a mouse user reads on hover and what several
      // screen readers fall back to, so leaving it in English undid the point of
      // translating the label beside it.
      document.querySelectorAll('[data-i18n-title]').forEach((el) => {
        el.setAttribute('title', this.t(el.getAttribute('data-i18n-title')));
      });
      // Placeholders. The grey text inside an empty field is the only
      // instruction some fields have, so leaving it in English leaves that
      // field unexplained in three of the four languages.
      document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
        el.setAttribute('placeholder', this.t(el.getAttribute('data-i18n-ph')));
      });
      if (LUMEN.UI && LUMEN.UI.game) { LUMEN.UI.refreshMenu(); LUMEN.UI.renderSettings && LUMEN.UI.renderSettings(); }
    },
  };
  LUMEN.i18n = I18N;
  LUMEN.t = (k, v) => I18N.t(k, v);
